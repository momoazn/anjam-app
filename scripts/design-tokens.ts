import { readFile, writeFile } from "node:fs/promises";
import { resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { dirname } from "node:path";

type Json = null | boolean | number | string | Json[] | { [key: string]: Json };

type LeafToken = string;
type TokensObject = Record<string, Json>;

const repoRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const tokensJsonPath = resolve(repoRoot, "src/design/tokens.json");
const tokensTsPath = resolve(repoRoot, "src/design/tokens.ts");
const indexCssPath = resolve(repoRoot, "src/index.css");

const START = "/* DESIGN SYSTEM TOKENS:START */";
const END = "/* DESIGN SYSTEM TOKENS:END */";

function escapeRegExp(value: string) {
  return value.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
}

function isRecord(value: unknown): value is Record<string, unknown> {
  return !!value && typeof value === "object" && !Array.isArray(value);
}

function flattenLeafTokens(
  value: Json,
  path: string[] = [],
  out: Array<{ key: string; value: LeafToken }> = [],
) {
  if (typeof value === "string") {
    out.push({ key: path.join("-"), value });
    return out;
  }

  if (isRecord(value)) {
    for (const [k, v] of Object.entries(value)) {
      flattenLeafTokens(v as Json, [...path, k], out);
    }
    return out;
  }

  throw new Error(
    `tokens.json must contain only nested objects with string leaves; found ${typeof value} at "${path.join(".") || "<root>"}"`,
  );
}

function tokensToTsObject(value: Json, path: string[] = []): string {
  return tokensToTsObjectWithIndent(value, path, 0);
}

function tokensToTsObjectWithIndent(
  value: Json,
  path: string[],
  indentLevel: number,
): string {
  if (typeof value === "string") {
    const cssVar = `--ds-${path.join("-")}`;
    return JSON.stringify(`var(${cssVar})`);
  }

  if (!isRecord(value)) {
    throw new Error(
      `tokens.json must contain only nested objects with string leaves; found ${typeof value} at "${path.join(".") || "<root>"}"`,
    );
  }

  const entries = Object.keys(value)
    .sort()
    .map((k) => {
      const v = value[k] as Json;
      const indent = "  ".repeat(indentLevel + 1);
      const key =
        /^[A-Za-z_$][A-Za-z0-9_$]*$/.test(k) && k !== "default"
          ? k
          : JSON.stringify(k);
      return `${indent}${key}: ${tokensToTsObjectWithIndent(
        v,
        [...path, k],
        indentLevel + 1,
      )},`;
    })
    .join("\n");

  const baseIndent = "  ".repeat(indentLevel);
  return `{\n${entries}\n${baseIndent}}`;
}

function generateTokensTs(tokensJson: TokensObject) {
  const tokensObject = tokensToTsObject(tokensJson);
  return `// This file is generated by \`bun run scripts/design-tokens.ts\` from \`src/design/tokens.json\`.
// Do not edit manually.

export const tokens = ${tokensObject} as const;

export type DesignTokens = typeof tokens;
`;
}

function generateCssVars(tokensJson: TokensObject) {
  const flat = flattenLeafTokens(tokensJson).sort((a, b) =>
    a.key.localeCompare(b.key),
  );

  return flat.map(({ key, value }) => `--ds-${key}: ${value};`).join("\n");
}

function replaceBetweenMarkers(content: string, replacement: string) {
  const pattern = new RegExp(
    `(^[\\t ]*)${escapeRegExp(START)}\\n[\\s\\S]*?\\n\\1${escapeRegExp(END)}`,
    "m",
  );

  const match = content.match(pattern);
  if (!match) {
    throw new Error(
      `Expected both markers in src/index.css on their own lines:\n${START}\n${END}`,
    );
  }

  const indent = match[1] ?? "";
  const replacementWithIndent = replacement
    .split("\n")
    .map((line) => (line.length ? `${indent}${line}` : line))
    .join("\n");

  return content.replace(
    pattern,
    `${indent}${START}\n${replacementWithIndent}\n${indent}${END}`,
  );
}

async function main() {
  const args = new Set(process.argv.slice(2));
  const check = args.has("--check");

  const tokensRaw = await readFile(tokensJsonPath, "utf8");
  const tokensJson = JSON.parse(tokensRaw) as Json;

  if (!isRecord(tokensJson)) {
    throw new Error("tokens.json root must be an object");
  }

  const nextTokensTs = generateTokensTs(tokensJson);
  const cssVars = generateCssVars(tokensJson);

  const indexCss = await readFile(indexCssPath, "utf8");
  const nextIndexCss = replaceBetweenMarkers(indexCss, cssVars);

  const currentTokensTs = await readFile(tokensTsPath, "utf8").catch(() => "");

  const tokensTsChanged = currentTokensTs !== nextTokensTs;
  const indexCssChanged = indexCss !== nextIndexCss;

  if (check) {
    if (tokensTsChanged || indexCssChanged) {
      const changed = [
        tokensTsChanged ? "src/design/tokens.ts" : null,
        indexCssChanged ? "src/index.css" : null,
      ].filter(Boolean);
      throw new Error(
        `Design tokens are out of date. Regenerate with \`bun run scripts/design-tokens.ts\`.\nChanged: ${changed.join(", ")}`,
      );
    }
    return;
  }

  await writeFile(tokensTsPath, nextTokensTs, "utf8");
  await writeFile(indexCssPath, nextIndexCss, "utf8");
}

main().catch((err) => {
  console.error(err instanceof Error ? err.message : err);
  process.exit(1);
});
